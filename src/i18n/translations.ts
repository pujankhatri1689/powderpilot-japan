export function translateLevel(
  level: "Beginner" | "Intermediate" | "Advanced",
  lang: Language
): string {
  if (lang === "ja") {
    return level === "Beginner"
      ? "初級"
      : level === "Intermediate"
      ? "中級"
      : "上級・パウダー";
  }
  if (lang === "zh") {
    return level === "Beginner"
      ? "初级"
      : level === "Intermediate"
      ? "中级"
      : "高级 / 粉雪";
  }
  return level;
}

