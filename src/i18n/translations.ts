export function translateRegion(
  region: Region | "All",
  lang: Language,
  withSuffix = false
): string {
  if (region === "All") {
    return lang === "ja" ? "すべて" : "All";
  }
  const map: Record<Region, { en: string; ja: string; jaPref: string }> = {
    Nagano: {
      en: "Nagano",
      ja: "長野",
      jaPref: "長野県",
    },
    Niigata: {
      en: "Niigata",
      ja: "新潟",
      jaPref: "新潟県",
    },
    Gunma: {
      en: "Gunma",
      ja: "群馬",
      jaPref: "群馬県",
    },
    Fukushima: {
      en: "Fukushima",
      ja: "福島",
      jaPref: "福島県",
    },
    Yamagata: {
      en: "Yamagata",
      ja: "山形",
      jaPref: "山形県",
    },
    Aomori: {
      en: "Aomori",
      ja: "青森",
      jaPref: "青森県",
    },
    Iwate: {
      en: "Iwate",
      ja: "岩手",
      jaPref: "岩手県",
    },
    Akita: {
      en: "Akita",
      ja: "秋田",
      jaPref: "秋田県",
    },
    Miyagi: {
      en: "Miyagi",
      ja: "宮城",
      jaPref: "宮城県",
    },
    Hokkaido: {
      en: "Hokkaido",
      ja: "北海道",
      jaPref: "北海道",
    },
    Gifu: {
      en: "Gifu",
      ja: "岐阜",
      jaPref: "岐阜県",
    },
    Shizuoka: {
      en: "Shizuoka",
      ja: "静岡",
      jaPref: "静岡県",
    },
    Shiga: {
      en: "Shiga",
      ja: "滋賀",
      jaPref: "滋賀県",
    },
  };
  const item = map[region];
  if (withSuffix) {
    if (lang === "ja") return item.jaPref;
    return `${item.en} Prefecture`;
  }
  return item[lang];
}

export function translateLevel(
  level: "Beginner" | "Intermediate" | "Advanced",
  lang: Language
): string {
  if (lang === "ja") {
    return level === "Beginner"
      ? "初級"
      : level === "Intermediate"
      ? "中級"
      : "上級・パウダー";
  }
  return level;
}

