export function getLocalizedResort(resort: Resort, lang: Language): Resort {
  if (lang === "en") return resort;
  const loc = RESORT_TRANSLATIONS[lang]?.[resort.slug];
  if (!loc) return resort;

  return {
    ...resort,
    name: loc.name,
    area: loc.area,
    description: loc.description,
    bestFor: loc.bestFor,
    vibeTags: loc.vibeTags,
    operatingHours: loc.operatingHours,
    pricing: {
      ...resort.pricing,
      seasonPassName: loc.pricing.seasonPassName,
      notes: loc.pricing.notes,
    },
    snowboarderIntel: loc.snowboarderIntel,
    mapGallery: resort.mapGallery.map((slide, idx) => {
      const locSlide = loc.mapGallery[idx];
      if (!locSlide) return slide;
      return {
        ...slide,
        title: locSlide.title,
        caption: locSlide.caption,
        badge: locSlide.badge ?? slide.badge,
      };
    }),
    signatureRuns: resort.signatureRuns.map((run, idx) => {
      const locRun = loc.signatureRuns[idx];
      if (!locRun) return run;
      return {
        ...run,
        name: locRun.name,
        note: locRun.note,
      };
    }),
    onsenAndVillage: resort.onsenAndVillage?.map((spot, idx) => {
      const locSpot = loc.onsenAndVillage?.[idx];
      if (!locSpot) return spot;
      return {
        ...spot,
        name: locSpot.name,
        description: locSpot.description,
        info: locSpot.info,
      };
    }),
    fromTokyo: {
      ...resort.fromTokyo,
      summary: loc.fromTokyo.summary,
      station: loc.fromTokyo.station,
    },
  };
}
